constexpr float peak_acceleration(bool yaw_axis)
{
  float peak = 0.0f;
  for (const TrajectoryPoint & point : kTrajectory) {
    const float value = yaw_axis ? point.yaw_acc : point.pitch_acc;
    const float magnitude = value < 0.0f ? -value : value;
    if (magnitude > peak) peak = magnitude;
  }
  return peak;
}
static_assert(TRAJECTORY_YAW_MAX_ACCELERATION_RAD_S2 > 0.0f &&
                TRAJECTORY_PITCH_MAX_ACCELERATION_RAD_S2 > 0.0f,
              "Acceleration limits must be positive");
static_assert(peak_acceleration(true) * kYawScale * kTimeScale * kTimeScale <=
                TRAJECTORY_YAW_MAX_ACCELERATION_RAD_S2,
              "Yaw acceleration exceeds limit; increase TRAJECTORY_PERIOD_MS");
static_assert(peak_acceleration(false) * kPitchScale * kTimeScale * kTimeScale <=
                TRAJECTORY_PITCH_MAX_ACCELERATION_RAD_S2,
              "Pitch acceleration exceeds limit; increase TRAJECTORY_PERIOD_MS");

constexpr TrajectoryPoint scale(const TrajectoryPoint & point)
{
  return {point.yaw * kYawScale, point.yaw_vel * kYawScale * kTimeScale,
          point.yaw_acc * kYawScale * kTimeScale * kTimeScale,
          point.pitch * kPitchScale, point.pitch_vel * kPitchScale * kTimeScale,
          point.pitch_acc * kPitchScale * kTimeScale * kTimeScale};
}
constexpr TrajectoryPoint kInitialPoint = scale(kTrajectory[0]);

void publish(const TrajectoryPoint & point)
{
  taskENTER_CRITICAL();
  yaw = point.yaw;
  yaw_vel = point.yaw_vel;
  yaw_acc = point.yaw_acc;
  pitch = point.pitch;
  pitch_vel = point.pitch_vel;
  pitch_acc = point.pitch_acc;
  taskEXIT_CRITICAL();
}
